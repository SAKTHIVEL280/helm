    private DotIcons() {}

    private static void def(String name, String... rows) {
        boolean[][] g = new boolean[rows.length][rows[0].length()];
        for (int r = 0; r < rows.length; r++) {
            for (int c = 0; c < rows[r].length(); c++) g[r][c] = rows[r].charAt(c) == '#';
        }
        ICONS.put(name, g);
    }

    /** Draws the icon centred on (cx, cy), {@code size} across. */
    static void draw(Canvas c, String name, float cx, float cy, float size, Paint p) {
        boolean[][] g = ICONS.get(name);
        if (g == null) return;
        int n = g.length;
        float pitch = size / n;
        float r = pitch * 0.42f;
        float x0 = cx - size / 2f, y0 = cy - size / 2f;
        for (int row = 0; row < n; row++) {
            for (int col = 0; col < g[row].length; col++) {
                if (g[row][col]) c.drawCircle(x0 + col * pitch + pitch / 2f, y0 + row * pitch + pitch / 2f, r, p);
            }
        }
    }
